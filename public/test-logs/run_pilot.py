#!/usr/bin/env python3
"""Pilot self-consistency test for AI Humanizer detector mode.

Protocol (see /bypass-test-methodology):
  1. Fixed sample set, generated by DeepSeek with a fixed prompt (recorded).
  2. Baseline: score each raw sample with the site's detector mode.
     Samples not flagged as AI are discarded.
  3. Rewrite each remaining sample with generic mode (temperature 1.3).
  4. Score the rewrite with detector mode (temperature 0.3).
  5. Pass = raw flagged AI AND rewrite judged human/below threshold.
     mixed / uncertain = fail. No regrading.

This is a SELF-CONSISTENCY check of one prompt-driven detector against
another prompt-driven rewriter, both on DeepSeek. It is NOT independent
verification and NOT evidence about GPTZero / Turnitin / other detectors.
"""

import hashlib
import json
import os
import re
import urllib.request
from datetime import datetime, timezone

KEY = open('/sessions/great-gracious-sagan/mnt/humanizer-site/.env.local').read().split('DEEPSEEK_API_KEY=', 1)[1].strip().splitlines()[0]
API = 'https://api.deepseek.com/chat/completions'
DATE = datetime.now(timezone.utc).strftime('%Y-%m-%d')
RUN_ID = f'SELF-{DATE}'
PROMPT_VERSION = 'v1.1'
STEM = 'generate plain English prose, no lists, no markdown, no title'

# Five categories from the published protocol, 6 samples each = 30 total.
TOPICS = [
    'academic_essay', 'academic_essay', 'academic_essay', 'academic_essay', 'academic_essay', 'academic_essay',
    'marketing_blog', 'marketing_blog', 'marketing_blog', 'marketing_blog', 'marketing_blog', 'marketing_blog',
    'professional_email', 'professional_email', 'professional_email', 'professional_email', 'professional_email', 'professional_email',
    'technical_docs', 'technical_docs', 'technical_docs', 'technical_docs', 'technical_docs', 'technical_docs',
    'non_native_english', 'non_native_english', 'non_native_english', 'non_native_english', 'non_native_english', 'non_native_english',
]
SUBJECTS = [
    'why peer review matters in scientific publishing',
    'the role of uncertainty in historical research',
    'how urban green spaces affect public health',
    'arguments for open data in university research',
    'the limits of standardized testing',
    'why citation practices differ across disciplines',
    'a product page for a reusable water bottle',
    'a blog intro about remote work routines',
    'a newsletter update for a small coffee roaster',
    'a landing page for a language learning app',
    'a short post about personal finance habits',
    'a campaign blurb for a local charity run',
    'following up after a job interview',
    'requesting a project status update from a colleague',
    'declining a meeting politely but firmly',
    'introducing a new teammate to a client',
    'confirming travel details for a conference',
    'thank-you note after a partnership call',
    'a README intro for an open source CLI tool',
    'release notes for a minor bugfix version',
    'a tutorial paragraph on using environment variables',
    'explaining a caching layer to new engineers',
    'documenting an API rate limit policy',
    'troubleshooting steps for a failed build',
    'an ESL student essay about climate change',
    'a non-native speaker email to a professor',
    'a short opinion piece about public transport',
    'a work update written by a non-native speaker',
    'a personal statement draft about studying abroad',
    'a reflection on learning a second language',
]


def call(messages, temperature, max_tokens):
    body = json.dumps({
        'model': 'deepseek-chat',
        'messages': messages,
        'temperature': temperature,
        'max_tokens': max_tokens,
    }).encode()
    req = urllib.request.Request(API, data=body, headers={
        'Content-Type': 'application/json',
        'Authorization': f'Bearer {KEY}',
    })
    with urllib.request.urlopen(req, timeout=90) as r:
        data = json.load(r)
    return data['choices'][0]['message']['content'].strip()


def generate(i, subject):
    prompt = (
        f'Write a single paragraph of about 200 words about {subject}. '
        f'{STEM}. Do not use bullet points or headings.'
    )
    return call([{'role': 'user', 'content': prompt}], 0.8, 700)


def rewrite(text):
    return call([
        {'role': 'system', 'content':
         'You are an expert editor rewriting AI-generated text so it reads like a human wrote it. '
         'Vary sentence length deliberately, use conversational transitions and occasional first-person '
         'voice, reduce list-like structure, avoid generic AI vocabulary, and preserve facts, names, '
         'numbers and citations exactly. Output ONLY the rewritten text.'},
        {'role': 'user', 'content': f'Rewrite the following text. Output only the rewrite:\n\n{text}'},
    ], 1.3, 1000)


def detect(text):
    schema = ('Output a strict JSON object only: {"ai_probability": integer 0-100, '
              '"human_probability": integer 0-100, "verdict": "Likely AI"|"Likely Human"|"Uncertain", '
              '"signals": [5 short strings], "explanation": string}. Be calibrated, not paranoid.')
    out = call([
        {'role': 'system', 'content': schema},
        {'role': 'user', 'content': f'Analyze this text for AI generation probability. Output only JSON:\n\n{text}'},
    ], 0.3, 700)
    cleaned = re.sub(r'^```(?:json)?\s*', '', out).replace('```', '').strip()
    try:
        parsed = json.loads(cleaned)
    except Exception:
        return {'verdict': 'PARSE_FAILURE', 'raw': out[:200]}
    return parsed


PASS_WORDS = ('likely human', 'human', 'not ai', 'below threshold')


def is_pass(raw_verdict, new_verdict):
    raw = raw_verdict.lower()
    new = new_verdict.lower()
    raw_flagged = 'ai' in raw and 'human' not in raw and 'uncertain' not in raw
    return raw_flagged and any(w in new for w in PASS_WORDS)


def main():
    samples = []
    records = []
    for i, (cat, subject) in enumerate(zip(TOPICS, SUBJECTS), 1):
        sid = f'{cat}-{i:03d}'
        raw = generate(i, subject)
        raw_hash = hashlib.sha256(raw.encode()).hexdigest()[:16]
        raw_d = detect(raw)
        rv = raw_d.get('verdict', 'PARSE_FAILURE')
        flagged = 'ai' in rv.lower() and 'human' not in rv.lower() and 'uncertain' not in rv.lower()
        rewritten = rewrite(raw)
        new_d = detect(rewritten)
        nv = new_d.get('verdict', 'PARSE_FAILURE')
        ok = is_pass(rv, nv)
        samples.append({
            'sample_id': sid, 'category': cat, 'subject': subject,
            'generation_prompt': f'Write a single paragraph of about 200 words about {subject}. {STEM}. Do not use bullet points or headings.',
            'raw_text': raw, 'rewritten_text': rewritten,
            'raw_detection': raw_d, 'rewritten_detection': new_d,
            'input_hash': raw_hash,
        })
        if flagged:
            records.append({
                'run_id': RUN_ID, 'date_utc': DATE,
                'detector': 'AI Humanizer detector (self-check)',
                'detector_version': f'prompt-{PROMPT_VERSION}/deepseek-chat',
                'sample_id': sid, 'category': cat,
                'raw_verdict': rv, 'rewritten_verdict': nv,
                'pass': 1 if ok else 0,
                'prompt_version': PROMPT_VERSION,
                'model': 'deepseek-chat', 'temperature': 0.3,
                'regraded': 0, 'input_hash': raw_hash, 'evidence_url': '',
            })
        print(f'{sid:38s} raw={rv:12s} new={nv:12s} pass={int(ok)}', flush=True)

    out = {
        'samples': samples,
        'records': records,
        'summary': {
            'generated': len(samples),
            'baseline_flagged': len(records),
            'passed': sum(r['pass'] for r in records),
            'pass_rate': round(sum(r['pass'] for r in records) / len(records) * 100, 1) if records else 0,
            'date': DATE,
            'run_id': RUN_ID,
            'detector': 'AI Humanizer detector (self-check)',
            'note': 'Self-consistency pilot. Not independent verification. Not about GPTZero/Turnitin.',
        },
    }
    base = '/sessions/great-gracious-sagan/mnt/outputs/test-run'
    with open(f'{base}/pilot-results.json', 'w') as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
    print('\nSUMMARY:', json.dumps(out['summary'], indent=2))


if __name__ == '__main__':
    main()
